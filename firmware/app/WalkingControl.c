// ======================= Simple Line Following (Grayscale over I2C1) =======================
// 输入：位图/重心；输出：动作码（1..6）
static uint8_t decide_action_from_grayscale(uint8_t mask, uint8_t cog)
{
  // 例：bit0=最左，bit7=最右；cog 0..7
  // 简单规则：居中(3..4)->直行；偏左->右微调；偏右->左微调；全黑/全白->定身或补偿
  if(mask==0x00){ return 6; }          // 丢线，定身/复位
  if(mask==0xFF){ return 1; }          // 全黑，按直行帧
  if(cog<=2){ return 3; }              // 线在左侧，右微调
  if(cog>=5){ return 2; }              // 线在右侧，左微调
  return 1;                            // 基本直行
}

